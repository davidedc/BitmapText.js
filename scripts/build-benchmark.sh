#!/bin/bash

# Build a Node.js performance benchmark (unbundled + bundled variants).
#
# Usage:
#   ./scripts/build-benchmark.sh <measurement|rendering>
#
# Available benchmarks:
#   measurement   — measureText() performance (no PNG output)
#   rendering     — drawTextFromAtlas() performance (PNG output for verification)
#
# Both variants previously lived in separate ~325-line scripts that shared the
# vast majority of their code; the rendering benchmark additionally pulls in the
# PNG encoder lib so it can write its sample frames. Collapsed here into one
# parameterised builder.

set -e  # Exit on any error

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

# --- Benchmark registry ---------------------------------------------------
KIND="${1:-}"
case "$KIND" in
  measurement)
    NICE_TITLE="Measurement Performance Benchmark"
    NICE_DESC="measureText() performance"
    MAIN_FILE="measurement-benchmark-main.js"
    BUNDLED_MAIN="measurement-benchmark-bundled-main.js"
    OUTPUT_PREFIX="measurement-benchmark"
    INCLUDE_PNG_CODEC=no
    ;;
  rendering)
    NICE_TITLE="Performance Benchmark"
    NICE_DESC="rendering performance"
    MAIN_FILE="rendering-benchmark-main.js"
    BUNDLED_MAIN="rendering-benchmark-bundled-main.js"
    OUTPUT_PREFIX="rendering-benchmark"
    INCLUDE_PNG_CODEC=yes
    ;;
  ""|-h|--help)
    echo "Usage: $0 <measurement|rendering>"
    exit 1
    ;;
  *)
    echo "Unknown benchmark kind: $KIND"
    echo "Available: measurement, rendering"
    exit 1
    ;;
esac

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Building $NICE_TITLE..."

# --- Paths ----------------------------------------------------------------
SRC_DIR="$PROJECT_ROOT/src"
LIB_DIR="$PROJECT_ROOT/lib"
OUTPUT_DIR="$PROJECT_ROOT/perf/node/dist"
UNBUNDLED_OUTPUT="$OUTPUT_DIR/$OUTPUT_PREFIX-unbundled.bundle.js"
BUNDLED_OUTPUT="$OUTPUT_DIR/$OUTPUT_PREFIX-bundled.js"

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Project root: $PROJECT_ROOT"

mkdir -p "$OUTPUT_DIR"

# Build the source-file list. Rendering pulls in the PNG codec; measurement
# doesn't (it never writes pixels out).
FILES_TO_CHECK=(
  "$SRC_DIR/platform/canvas-mock.js"
  "$SRC_DIR/runtime/StatusCode.js"
  "$SRC_DIR/runtime/FontProperties.js"
  "$SRC_DIR/runtime/TextProperties.js"
  "$SRC_DIR/runtime/FontMetrics.js"
  "$SRC_DIR/runtime/InterpolatedFontMetrics.js"
  "$SRC_DIR/runtime/CharacterSets.js"
  "$SRC_DIR/builder/MetricsExpander.js"
  "$SRC_DIR/runtime/AtlasPositioning.js"
  "$SRC_DIR/runtime/AtlasImage.js"
  "$SRC_DIR/runtime/AtlasData.js"
  "$SRC_DIR/utils/AtlasCellDimensions.js"
  "$LIB_DIR/QOIDecode.js"
  "$SRC_DIR/runtime/AtlasDataStore.js"
  "$SRC_DIR/runtime/PositioningBundleStore.js"
  "$SRC_DIR/runtime/FontMetricsStore.js"
  "$SRC_DIR/runtime/FontLoaderBase.js"
  "$SRC_DIR/platform/FontLoaderNode.js"
  "$SRC_DIR/runtime/BitmapText.js"
  "$SRC_DIR/runtime/BitmapTextRegistration.js"
  "$SRC_DIR/shared/test-data.js"
  "$SRC_DIR/node/$MAIN_FILE"
)
if [[ "$INCLUDE_PNG_CODEC" == "yes" ]]; then
  FILES_TO_CHECK+=("$LIB_DIR/PngEncodingOptions.js" "$LIB_DIR/PngEncoder.js")
fi

verify_files "${FILES_TO_CHECK[@]}"
echo "[$(date '+%Y-%m-%d %H:%M:%S')] All source files found ✓"

# Helper: append a //-banner + cat to $1 (output file).
section() {
  local out="$1"
  local title="$2"
  local file="$3"
  local strip_first_line="${4:-no}"
  {
    echo "// ============================================================================"
    echo "// $title"
    echo "// ============================================================================"
    if [[ "$strip_first_line" == "yes" ]]; then
      tail -n +2 "$file"
    else
      cat "$file"
    fi
    echo ""
  } >> "$out"
}

# ==========================================================================
# UNBUNDLED variant — all source files concatenated into one self-contained
# executable. No external requires.
# ==========================================================================
echo "[$(date '+%Y-%m-%d %H:%M:%S')] Building UNBUNDLED version..."

cat > "$UNBUNDLED_OUTPUT" << EOF
#!/usr/bin/env node

/**
 * ⚠️  THIS IS A BUNDLED/BUILT FILE - DO NOT EDIT ⚠️
 *
 * BitmapText.js $NICE_TITLE - Unbundled Version
 *
 * This file is automatically generated by concatenating multiple source files.
 * Tests $NICE_DESC with all source files concatenated.
 *
 * Usage:
 *   node perf/node/dist/$OUTPUT_PREFIX-unbundled.bundle.js
 *
 * Output:
 *   JSON results to stdout
 *
 * Generated by: scripts/build-benchmark.sh $KIND
 */

// ============================================================================
EOF

section "$UNBUNDLED_OUTPUT" "MINIMAL CANVAS MOCK"                    "$SRC_DIR/platform/canvas-mock.js" yes
section "$UNBUNDLED_OUTPUT" "STATUS CODE CONSTANTS"                  "$SRC_DIR/runtime/StatusCode.js"
section "$UNBUNDLED_OUTPUT" "FONT PROPERTIES CLASS"                  "$SRC_DIR/runtime/FontProperties.js"
section "$UNBUNDLED_OUTPUT" "TEXT PROPERTIES CLASS"                  "$SRC_DIR/runtime/TextProperties.js"
section "$UNBUNDLED_OUTPUT" "FONT METRICS CLASS"                     "$SRC_DIR/runtime/FontMetrics.js"
section "$UNBUNDLED_OUTPUT" "INTERPOLATED FONT METRICS CLASS"        "$SRC_DIR/runtime/InterpolatedFontMetrics.js"
section "$UNBUNDLED_OUTPUT" "CHARACTER SETS CONFIGURATION"           "$SRC_DIR/runtime/CharacterSets.js"

# BitmapText + its registration glue (emitted together to match original layout).
{
  echo "// ============================================================================"
  echo "// BITMAP TEXT STATIC CLASS"
  echo "// ============================================================================"
  cat "$SRC_DIR/runtime/BitmapText.js"
  cat "$SRC_DIR/runtime/BitmapTextRegistration.js"
  echo ""
} >> "$UNBUNDLED_OUTPUT"

section "$UNBUNDLED_OUTPUT" "METRICS EXPANDER"                       "$SRC_DIR/builder/MetricsExpander.js"
section "$UNBUNDLED_OUTPUT" "ATLAS POSITIONING CLASS"                "$SRC_DIR/runtime/AtlasPositioning.js"
section "$UNBUNDLED_OUTPUT" "ATLAS IMAGE CLASS"                      "$SRC_DIR/runtime/AtlasImage.js"
section "$UNBUNDLED_OUTPUT" "ATLAS DATA CLASS"                       "$SRC_DIR/runtime/AtlasData.js"
section "$UNBUNDLED_OUTPUT" "ATLAS CELL DIMENSIONS"                  "$SRC_DIR/utils/AtlasCellDimensions.js"
section "$UNBUNDLED_OUTPUT" "QOI DECODER"                            "$LIB_DIR/QOIDecode.js"
section "$UNBUNDLED_OUTPUT" "ATLAS DATA STORE"                       "$SRC_DIR/runtime/AtlasDataStore.js"
section "$UNBUNDLED_OUTPUT" "POSITIONING BUNDLE STORE"               "$SRC_DIR/runtime/PositioningBundleStore.js"
section "$UNBUNDLED_OUTPUT" "FONT METRICS STORE"                     "$SRC_DIR/runtime/FontMetricsStore.js"
section "$UNBUNDLED_OUTPUT" "FONT LOADER BASE"                       "$SRC_DIR/runtime/FontLoaderBase.js"
section "$UNBUNDLED_OUTPUT" "FONT LOADER - NODE.JS"                  "$SRC_DIR/platform/FontLoaderNode.js"

if [[ "$INCLUDE_PNG_CODEC" == "yes" ]]; then
  section "$UNBUNDLED_OUTPUT" "PNG ENCODING OPTIONS"                 "$LIB_DIR/PngEncodingOptions.js"
  section "$UNBUNDLED_OUTPUT" "PNG ENCODER"                          "$LIB_DIR/PngEncoder.js"
fi

section "$UNBUNDLED_OUTPUT" "TEST DATA"                              "$SRC_DIR/shared/test-data.js"
section "$UNBUNDLED_OUTPUT" "BENCHMARK LOGIC"                        "$SRC_DIR/node/$MAIN_FILE" yes

chmod +x "$UNBUNDLED_OUTPUT"

UNBUNDLED_SIZE=$(wc -c < "$UNBUNDLED_OUTPUT" | tr -d ' ')
UNBUNDLED_LINES=$(wc -l < "$UNBUNDLED_OUTPUT" | tr -d ' ')

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Unbundled build completed! ✅"
echo "  Output: $UNBUNDLED_OUTPUT"
echo "  Size:   $UNBUNDLED_SIZE bytes"
echo "  Lines:  $UNBUNDLED_LINES"
echo ""

# ==========================================================================
# BUNDLED variant — uses production runtime bundle via require(). The bundled
# main strips its require()s; we re-add a thin shim plus the runtime bundle.
# ==========================================================================
echo "[$(date '+%Y-%m-%d %H:%M:%S')] Building BUNDLED version..."

cat > "$BUNDLED_OUTPUT" << EOF
#!/usr/bin/env node

/**
 * ⚠️  THIS IS A BUNDLED/BUILT FILE - DO NOT EDIT ⚠️
 *
 * BitmapText.js $NICE_TITLE - Bundled Version
 *
 * This version uses the production runtime bundle.
 *
 * Usage:
 *   node perf/node/dist/$OUTPUT_PREFIX-bundled.js
 *
 * Output:
 *   JSON results to stdout
 *
 * Generated by: scripts/build-benchmark.sh $KIND
 */

// ============================================================================
// USER-PROVIDED DEPENDENCIES
// ============================================================================

EOF

# Add Canvas mock (without module.exports — the bundled main wires its own scope)
grep -v "module.exports" "$SRC_DIR/platform/canvas-mock.js" >> "$BUNDLED_OUTPUT"
echo "" >> "$BUNDLED_OUTPUT"

# Wire in the runtime bundle + Node built-ins + test data + benchmark body.
{
  echo "// ============================================================================"
  echo "// LIBRARY RUNTIME BUNDLE"
  echo "// ============================================================================"
  echo ""
  echo "require('../../../dist/bitmaptext-node.min.js');"
  echo ""
  echo "// ============================================================================"
  echo "// NODE.JS BUILT-IN MODULES"
  echo "// ============================================================================"
  echo ""
  echo "const fs = require('fs');"
  echo "const path = require('path');"
  echo ""
  echo "// ============================================================================"
  echo "// TEST DATA"
  echo "// ============================================================================"
  cat "$SRC_DIR/shared/test-data.js"
  echo ""
  echo "// ============================================================================"
  echo "// BENCHMARK LOGIC"
  echo "// ============================================================================"
  echo ""
  # Strip the bundled main's header (first 22 lines) and the requires it would
  # otherwise duplicate.
  tail -n +23 "$SRC_DIR/node/$BUNDLED_MAIN" | \
    grep -v "const { Canvas }" | \
    grep -v "require('.*bitmaptext-node" | \
    grep -v "const fs = require" | \
    grep -v "const path = require" | \
    grep -v "^// ======"
} >> "$BUNDLED_OUTPUT"

chmod +x "$BUNDLED_OUTPUT"

BUNDLED_SIZE=$(wc -c < "$BUNDLED_OUTPUT" | tr -d ' ')
BUNDLED_LINES=$(wc -l < "$BUNDLED_OUTPUT" | tr -d ' ')

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Bundled build completed! ✅"
echo "  Output: $BUNDLED_OUTPUT"
echo "  Size:   $BUNDLED_SIZE bytes"
echo "  Lines:  $BUNDLED_LINES"
echo ""

# --- Summary ---------------------------------------------------------------
echo "[$(date '+%Y-%m-%d %H:%M:%S')] All $KIND benchmarks built successfully! ✅"
echo ""
echo "Output files:"
echo "  Unbundled: $UNBUNDLED_OUTPUT ($UNBUNDLED_SIZE bytes)"
echo "  Bundled:   $BUNDLED_OUTPUT ($BUNDLED_SIZE bytes)"
echo ""
echo "To run:"
echo "  node $UNBUNDLED_OUTPUT"
echo "  node $BUNDLED_OUTPUT"
