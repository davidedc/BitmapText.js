#!/bin/bash

# Build a standalone Node.js demo bundle (no external deps — all runtime + libs
# concatenated into one self-contained .js).
#
# Usage:
#   ./scripts/build-node-demo.sh <demo-name>
#
# Available demos (see DEMO_REGISTRY below):
#   hello-world     — Hello World, single size
#   multi-size      — Hello World, multi-size (18, 18.5, 19)
#   small-sizes     — Small Font Sizes Interpolation (< 9px)
#
# All three previously lived in separate ~310-line scripts; they shared the same
# file list and concatenation order, differing only in entry-point .js and output
# filename. Collapsed here into one parameterised builder.

set -e  # Exit on any error

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

# --- Demo registry --------------------------------------------------------
# Each demo: human description / src/node entry-point / output filename.
DEMO="${1:-}"
case "$DEMO" in
  hello-world)
    DEMO_DESC="Hello World Single Size"
    MAIN_FILE="hello-world-main.js"
    OUTPUT_NAME="hello-world.bundle.js"
    ;;
  multi-size)
    DEMO_DESC="Hello World Multi-Size"
    MAIN_FILE="hello-world-multi-size-main.js"
    OUTPUT_NAME="hello-world-multi-size.bundle.js"
    ;;
  small-sizes)
    DEMO_DESC="Small Font Sizes Interpolation"
    MAIN_FILE="small-sizes-main.js"
    OUTPUT_NAME="small-sizes.bundle.js"
    ;;
  ""|-h|--help)
    echo "Usage: $0 <hello-world|multi-size|small-sizes>"
    exit 1
    ;;
  *)
    echo "Unknown demo: $DEMO"
    echo "Available: hello-world, multi-size, small-sizes"
    exit 1
    ;;
esac

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Building Node.js demo: $DEMO_DESC..."

# --- Paths ----------------------------------------------------------------
SRC_DIR="$PROJECT_ROOT/src"
LIB_DIR="$PROJECT_ROOT/lib"
OUTPUT_DIR="$PROJECT_ROOT/examples/node/dist"
OUTPUT_FILE="$OUTPUT_DIR/$OUTPUT_NAME"

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Project root: $PROJECT_ROOT"
echo "[$(date '+%Y-%m-%d %H:%M:%S')] Output file:  $OUTPUT_FILE"

mkdir -p "$OUTPUT_DIR"

# --- Source files (kept identical to the originals — same order + same list).
FILES_TO_CHECK=(
  "$SRC_DIR/platform/canvas-mock.js"
  "$SRC_DIR/runtime/StatusCode.js"
  "$SRC_DIR/runtime/FontProperties.js"
  "$SRC_DIR/runtime/TextProperties.js"
  "$SRC_DIR/runtime/FontMetrics.js"
  "$SRC_DIR/runtime/InterpolatedFontMetrics.js"
  "$SRC_DIR/runtime/CharacterSets.js"
  "$SRC_DIR/builder/MetricsExpander.js"
  "$SRC_DIR/runtime/AtlasPositioning.js"
  "$SRC_DIR/runtime/AtlasImage.js"
  "$SRC_DIR/runtime/AtlasData.js"
  "$SRC_DIR/utils/AtlasCellDimensions.js"
  "$LIB_DIR/QOIDecode.js"
  "$SRC_DIR/runtime/AtlasDataStore.js"
  "$SRC_DIR/runtime/MetricsBundleStore.js"
  "$SRC_DIR/runtime/BundleCodec.js"
  "$SRC_DIR/runtime/PositioningBundleStore.js"
  "$SRC_DIR/runtime/FontMetricsStore.js"
  "$SRC_DIR/runtime/FontLoaderBase.js"
  "$SRC_DIR/platform/FontLoaderNode.js"
  "$LIB_DIR/PngEncodingOptions.js"
  "$LIB_DIR/PngEncoder.js"
  "$SRC_DIR/runtime/BitmapText.js"
  "$SRC_DIR/runtime/BitmapTextRegistration.js"
  "$SRC_DIR/node/_demo-helpers.js"
  "$SRC_DIR/node/$MAIN_FILE"
)

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Checking source files..."
verify_files "${FILES_TO_CHECK[@]}"
echo "[$(date '+%Y-%m-%d %H:%M:%S')] All source files found ✓"

# --- Build the output -----------------------------------------------------
echo "[$(date '+%Y-%m-%d %H:%M:%S')] Concatenating files..."

cat > "$OUTPUT_FILE" << EOF
#!/usr/bin/env node

/**
 * ⚠️  THIS IS A BUNDLED/BUILT FILE - DO NOT EDIT ⚠️
 *
 * BitmapText.js Node.js Demo - $DEMO_DESC
 *
 * Generated by concatenating multiple source files into one self-contained
 * executable. Source files live in src/runtime/, src/platform/, src/builder/,
 * lib/, and src/node/$MAIN_FILE.
 *
 * To modify this demo:
 *   1. Edit the source files.
 *   2. Run: ./scripts/build-node-demo.sh $DEMO
 *
 * Usage:
 *   node examples/node/dist/$OUTPUT_NAME
 */

// ============================================================================
EOF

# Canvas mock (strip first line: it's a //-comment header from the source)
section "$OUTPUT_FILE" "MINIMAL CANVAS MOCK - Only what BitmapText.js needs" "$SRC_DIR/platform/canvas-mock.js" yes

# Runtime classes (must come in dependency order)
section "$OUTPUT_FILE" "STATUS CODE CONSTANTS AND HELPERS"             "$SRC_DIR/runtime/StatusCode.js"
section "$OUTPUT_FILE" "FONT PROPERTIES CLASS"                         "$SRC_DIR/runtime/FontProperties.js"
section "$OUTPUT_FILE" "TEXT PROPERTIES CLASS"                         "$SRC_DIR/runtime/TextProperties.js"
section "$OUTPUT_FILE" "FONT METRICS CLASS"                            "$SRC_DIR/runtime/FontMetrics.js"
section "$OUTPUT_FILE" "INTERPOLATED FONT METRICS CLASS"               "$SRC_DIR/runtime/InterpolatedFontMetrics.js"
section "$OUTPUT_FILE" "CHARACTER SETS CONFIGURATION"                  "$SRC_DIR/runtime/CharacterSets.js"

# BitmapText (depends on CharacterSets) — emitted together with its registration glue.
{
  echo "// ============================================================================"
  echo "// BITMAP TEXT STATIC CLASS"
  echo "// ============================================================================"
  echo ""
  cat "$SRC_DIR/runtime/BitmapText.js"
  cat "$SRC_DIR/runtime/BitmapTextRegistration.js"
  echo ""
} >> "$OUTPUT_FILE"

section "$OUTPUT_FILE" "EXPANSION UTILITY - MetricsExpander.js"        "$SRC_DIR/builder/MetricsExpander.js"
section "$OUTPUT_FILE" "ATLAS POSITIONING CLASS"                       "$SRC_DIR/runtime/AtlasPositioning.js"
section "$OUTPUT_FILE" "ATLAS IMAGE CLASS"                             "$SRC_DIR/runtime/AtlasImage.js"
section "$OUTPUT_FILE" "ATLAS DATA CLASS"                              "$SRC_DIR/runtime/AtlasData.js"
section "$OUTPUT_FILE" "ATLAS CELL DIMENSIONS UTILITY"                 "$SRC_DIR/utils/AtlasCellDimensions.js"
section "$OUTPUT_FILE" "QOI DECODER LIBRARY"                           "$LIB_DIR/QOIDecode.js"
section "$OUTPUT_FILE" "ATLAS DATA STORE"                              "$SRC_DIR/runtime/AtlasDataStore.js"
section "$OUTPUT_FILE" "METRICS BUNDLE STORE"                          "$SRC_DIR/runtime/MetricsBundleStore.js"
section "$OUTPUT_FILE" "BUNDLE CODEC"                                  "$SRC_DIR/runtime/BundleCodec.js"
section "$OUTPUT_FILE" "POSITIONING BUNDLE STORE"                      "$SRC_DIR/runtime/PositioningBundleStore.js"
section "$OUTPUT_FILE" "FONT METRICS STORE"                            "$SRC_DIR/runtime/FontMetricsStore.js"
section "$OUTPUT_FILE" "FONT LOADER BASE CLASS"                        "$SRC_DIR/runtime/FontLoaderBase.js"
section "$OUTPUT_FILE" "FONT LOADER - NODE.JS PLATFORM IMPLEMENTATION" "$SRC_DIR/platform/FontLoaderNode.js"
section "$OUTPUT_FILE" "PNG ENCODING OPTIONS"                          "$LIB_DIR/PngEncodingOptions.js"
section "$OUTPUT_FILE" "PNG ENCODER"                                   "$LIB_DIR/PngEncoder.js"

# Helpers shared by all Node demos / benchmarks (getStatusName, measure*).
section "$OUTPUT_FILE" "DEMO HELPERS"                                  "$SRC_DIR/node/_demo-helpers.js"

# Main execution (strip first line: source has its own //-comment header)
section "$OUTPUT_FILE" "MAIN EXECUTION - $DEMO_DESC"                   "$SRC_DIR/node/$MAIN_FILE" yes

chmod +x "$OUTPUT_FILE"

FILE_SIZE=$(wc -c < "$OUTPUT_FILE" | tr -d ' ')
LINE_COUNT=$(wc -l < "$OUTPUT_FILE" | tr -d ' ')

echo "[$(date '+%Y-%m-%d %H:%M:%S')] Build completed successfully! ✅"
echo ""
echo "Output: $OUTPUT_FILE"
echo "Size:   $FILE_SIZE bytes"
echo "Lines:  $LINE_COUNT"
echo ""
echo "To run the demo:"
echo "  cd $PROJECT_ROOT"
echo "  node examples/node/dist/$OUTPUT_NAME"
echo ""
echo "To rebuild:"
echo "  ./scripts/build-node-demo.sh $DEMO"
